create function public.claim_google_sheets_sync_batch_v2(
  batch_size integer default 50,
  p_google_sheet_id text default null
)
returns table(
  event_id bigint,
  occurrence_sync_id uuid,
  sync_version bigint,
  unidade_id uuid,
  unidade_sigla text,
  google_sheet_id text,
  aba_principal text,
  payload jsonb,
  attempts integer
)
language plpgsql
security definer
set search_path = ''
as $function$
begin
  return query
  with chosen as (
    select q.id
    from public.google_sheets_sync_outbox q
    join public.unidades_integracoes i
      on i.unidade_id = q.unidade_id
     and i.tipo = 'GOOGLE_SHEETS_OCORRENCIAS'
     and i.ativo = true
    where q.status in ('PENDENTE', 'ERRO')
      and q.next_attempt_at <= now()
      and (p_google_sheet_id is null or i.google_sheet_id = p_google_sheet_id)
    order by q.id
    limit greatest(1, least(batch_size, 200))
    for update of q skip locked
  ),
  changed as (
    update public.google_sheets_sync_outbox q
       set attempts = q.attempts + 1,
           status = 'PENDENTE',
           next_attempt_at = now() + interval '5 minutes'
      from chosen c
     where q.id = c.id
    returning q.id, q.occurrence_sync_id, q.sync_version, q.unidade_id, q.payload, q.attempts
  )
  select
    c.id,
    c.occurrence_sync_id,
    c.sync_version,
    c.unidade_id,
    u.sigla,
    i.google_sheet_id,
    i.aba_principal,
    c.payload,
    c.attempts
  from changed c
  join public.unidades u
    on u.id = c.unidade_id
  join public.unidades_integracoes i
    on i.unidade_id = c.unidade_id
   and i.tipo = 'GOOGLE_SHEETS_OCORRENCIAS'
   and i.ativo = true
  where p_google_sheet_id is null or i.google_sheet_id = p_google_sheet_id
  order by c.id;
end
$function$;

revoke all on function public.claim_google_sheets_sync_batch_v2(integer, text)
  from public, anon, authenticated;
grant execute on function public.claim_google_sheets_sync_batch_v2(integer, text)
  to service_role;

create function public.obter_planilha_usuario()
returns table(
  unidade_id uuid,
  unidade_sigla text,
  google_sheet_id text,
  aba_principal text,
  google_sheet_url text
)
language sql
stable
security definer
set search_path = ''
as $function$
  select
    u.id,
    u.sigla,
    i.google_sheet_id,
    i.aba_principal,
    'https://docs.google.com/spreadsheets/d/' || i.google_sheet_id || '/edit'
  from public.perfis_usuarios p
  join public.unidades u
    on u.id = p.unidade_id
   and u.ativo = true
  join public.unidades_integracoes i
    on i.unidade_id = u.id
   and i.tipo = 'GOOGLE_SHEETS_OCORRENCIAS'
   and i.ativo = true
  where p.user_id = (select auth.uid())
    and p.ativo = true
  limit 1
$function$;

