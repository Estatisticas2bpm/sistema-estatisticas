const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'..');
const ler=p=>fs.readFileSync(path.join(base,p),'utf8');
const cfg=ler('auth-config.js');
const admin=ler('supabase/functions/admin-users/index.ts');
const usuarios=ler('usuarios.html');
const consulta=ler('consulta.html');
const dashboard=ler('dashboard.html');
const relatorio=ler('relatorio.html');
const perfis=ler('supabase/migrations/20261020124000_perfil_comandante_somente_leitura.sql');
const escopo=ler('supabase/migrations/20261020124500_comandante_escopo_unidade_principal.sql');
assert.ok(cfg.includes('COMANDANTE: ["consulta","dashboard","analise","mapa","relatorio"]'));
assert.ok(!cfg.includes('GESTOR:'));
assert.ok(usuarios.includes('value="COMANDANTE"'));
assert.ok(!usuarios.includes('value="GESTOR"'));
assert.ok(admin.includes('"COMANDANTE", "CONSULTA"'));
assert.ok(perfis.includes("CHECK (perfil IN ('ADMIN','ESTATISTICA','OPERADOR','COMANDANTE','CONSULTA'))"));
assert.ok(escopo.includes("if v_perfil IN ('ADMIN','COMANDANTE') then"));
assert.ok(consulta.includes("podeEditar=auth.pode('cadastro')"));
assert.ok(consulta.includes('class="btnVisualizar"'));
assert.ok(consulta.includes('if (!botao || !podeEditar) return;'));
assert.ok(dashboard.includes("gerarPdf.onclick=()=>location.href='relatorio.html"));
assert.ok(relatorio.includes('window.print()'));
console.log('Perfil COMANDANTE read-only e relatorios validados.');
