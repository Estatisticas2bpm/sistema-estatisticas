const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const root = path.join(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const config = read("auth-config.js");
const guard = read("auth-guard.js");
const home = read("index.html");
const dashboard = read("dashboard-cpc.html");
const page = read("ia-cpc.html");
const fn = read("supabase/functions/ia-cpc/index.ts");
const agregados = read("supabase/functions/ia-cpc/estatisticas.mjs");
const quota = read("docs/sql/ia_cpc_cota_pendente_aprovacao.sql");

assert.match(config, /"ia-cpc\.html"\s*:\s*"ia_cpc"/);
assert.match(guard, /permissao==='ia_cpc'/);
assert.match(guard, /normalizarPerfil\(perfil\)==='ADMIN'/);
assert.match(guard, /normalizarPerfil\(perfil\)==='COMANDANTE'&&String\(contextoAtual\?\.sigla\|\|''\)\.toUpperCase\(\)==='CPC'/);
assert.match(home, /href="ia-cpc\.html" data-permission="ia_cpc" hidden/);
assert.match(dashboard, /href="ia-cpc\.html" data-permission="ia_cpc" hidden/);
assert.match(page, /autorizado\.pode\('ia_cpc'\)/);
assert.match(page, /functions\.invoke\('ia-cpc'/);
assert.doesNotMatch(page, /OPENAI_API_KEY|service_role|sk-proj-/i);
assert.match(fn, /IA_CPC_ENABLED.*!== "true"/);
assert.match(fn, /admin\.auth\.getUser\(token\)/);
assert.match(fn, /\.from\("perfis_usuarios"\)/);
assert.match(fn, /papel === "ADMIN"/);
assert.match(fn, /papel === "COMANDANTE"/);
assert.match(fn, /normalizar\(unidade\.sigla\) === "CPC"/);
assert.match(fn, /return respostaJson\(403/);
assert.match(fn, /store: false/);
assert.match(fn, /MAX_REGISTROS = 10000/);
assert.match(agregados, /quantidade >= 5/);
assert.match(fn, /ia_cpc_reservar_cota/);
assert.match(fn, /erroCota/);
assert.match(quota, /pg_advisory_xact_lock/);
assert.match(quota, /REVOKE ALL ON FUNCTION public\.ia_cpc_reservar_cota\(uuid\) FROM PUBLIC, anon, authenticated/);
assert.match(quota, /v_dia >= 20 OR v_mes >= 300/);
assert.match(fn, /conducoesOperacionaisPorOcorrencia/);
assert.match(fn, /bairroPermitido/);
assert.doesNotMatch(fn, /historico_resumido|numero_bo|endereco_formatado|vitima_nome|infrator_nome/);
console.log("OK — política IA exclusiva ADMIN e COMANDANTE CPC verificada estruturalmente.");
