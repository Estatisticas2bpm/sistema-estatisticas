  id bigint generated by default as identity primary key,
  unidade_id uuid not null,
  tipo text not null,
  google_sheet_id text,
  aba_principal text not null default 'Ocorrências',
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint unidades_integracoes_unidade_fkey
    foreign key (unidade_id) references public.unidades(id)
    on update restrict on delete restrict,
  constraint unidades_integracoes_tipo_chk
    check (tipo = upper(tipo) and btrim(tipo) <> ''),
  constraint unidades_integracoes_sheet_chk
    check (
      tipo <> 'GOOGLE_SHEETS_OCORRENCIAS'
      or (google_sheet_id is not null and btrim(google_sheet_id) <> '')
    ),
  constraint unidades_integracoes_unidade_tipo_uq
    unique (unidade_id, tipo)
);

