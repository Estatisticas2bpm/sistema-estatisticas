create or replace function public.enqueue_occurrence_for_google_sheets()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if current_setting('app.google_sheets_ack', true) = '1' then
    return new;
  end if;

  if tg_op = 'INSERT'
     or public.occurrence_business_payload(new)
        is distinct from public.occurrence_business_payload(old) then
    insert into public.google_sheets_sync_outbox
      (occurrence_sync_id, sync_version, unidade_id, payload)
    values
      (new.sync_id, new.sync_version, new.unidade_id, to_jsonb(new))
    on conflict (occurrence_sync_id, sync_version)
    do update
      set unidade_id = excluded.unidade_id,
          payload = excluded.payload,
          status = 'PENDENTE',
          next_attempt_at = now(),
          last_error = null;
  end if;

  return new;
end
$function$;

revoke all on function public.enqueue_occurrence_for_google_sheets()
  from public, anon, authenticated;
grant execute on function public.enqueue_occurrence_for_google_sheets()
  to service_role;

create or replace function public.enqueue_deleted_occurrence_for_google_sheets()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  insert into public.google_sheets_sync_outbox
    (occurrence_sync_id, sync_version, unidade_id, payload, status, next_attempt_at, last_error)
  values
    (
      old.sync_id,
      old.sync_version + 1,
      old.unidade_id,
      to_jsonb(old) || jsonb_build_object('_deleted', true),
      'PENDENTE',
      now(),
      null
    )
  on conflict (occurrence_sync_id, sync_version)
  do update
    set unidade_id = excluded.unidade_id,
        payload = excluded.payload,
        status = 'PENDENTE',
        next_attempt_at = now(),
        last_error = null;

  return old;
end
$function$;

revoke all on function public.enqueue_deleted_occurrence_for_google_sheets()
